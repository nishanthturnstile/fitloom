import { writeFileSync } from "node:fs";
import { getConstructionPlans } from "pg-boss";
// Drizzle owns the outer transaction. Keep pg-boss's lock and all install statements.
export const queueSql = getConstructionPlans("pgboss")
  .replace(/^\s*BEGIN;/, "")
  .replace(/COMMIT;\s*$/, "")
  .trim();
if (process.argv[1] === new URL(import.meta.url).pathname) {
  writeFileSync(
    new URL("../migrations/0002_queue_install.sql", import.meta.url),
    `-- Generated by pg-boss 12.38.0. Outer transaction owned by Drizzle.\n${queueSql}\nREVOKE ALL ON SCHEMA pgboss FROM PUBLIC;\nREVOKE ALL ON ALL TABLES IN SCHEMA pgboss FROM PUBLIC;\nREVOKE ALL ON ALL FUNCTIONS IN SCHEMA pgboss FROM PUBLIC;\n`,
  );
}
